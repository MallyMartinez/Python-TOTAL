"""
O P E R A C I O  N E S   M A T E M A T I C A S 
    las operadores matemáticos básicos de Python, 
    que utilizaremos para realizar cálculos:
"""
x = 6
y = 2
z = 7

"Suma: +"
print(f"{x} + {y} = {x + y}")


"Resta: -"
print(f"{x} - {y} = {x - y}")


"Multiplicación: *"
print(f"{x} * {y} = {x * y}")


"División: /"
print(f"{x} / {y} = {x / y}")


"Cociente (division 'al  piso') //"
print(f"{z} // {y} = {z // y}")


"Resto (módulo) % (Util para detectar valores pares)"
print(f"{z} % {y} = {z % y}")


"Potencia: **"
print(f"{x} ** {y} = {x ** y}")

"Raiz cuadrada: **0.5 (Es un caso especial de potencia)"
print(f"{x} ** 0.5 = {x ** 0.5}")